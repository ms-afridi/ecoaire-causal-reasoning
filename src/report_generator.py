import json
from datetime import datetime, timezone
from typing import Dict, Any, Optional


def _fmt_score(value: Optional[float]) -> str:
    return "n/a" if value is None else f"`{value:.2f} / 1.00`"


def generate_markdown_report(
    extraction_data: Dict[str, Any],
    simulation_data: Optional[Dict[str, Any]] = None,
    sim_params: Optional[Dict[str, str]] = None,
) -> str:
    """
    Compiles a structured Scientific Hypothesis & Causal Assessment Report (.md)
    for one-click download.
    """
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    eval_metrics = extraction_data.get("evaluation", {})
    diag = extraction_data.get("graph_diagnostics") or {}

    lines = [
        "# EcoAIRE Scientific Hypothesis & Causal Reasoning Report",
        f"**Generated by:** EcoAIRE-Lite Prototype (TIB Hannover Doctoral Application — Ref. 44/2026)  ",
        f"**Author:** Md Shahid Afridi (`github.com/ms-afridi`)  ",
        f"**Timestamp:** {timestamp}  ",
        f"**Model:** {extraction_data.get('model_name', 'N/A')} (judge: {extraction_data.get('judge_model', 'N/A')}) — result source: {extraction_data.get('source', 'live')}",
        "",
        "> Prototype output. Sample papers are synthetic illustrative abstracts. Provenance is verified in code; "
        "rigor and completeness scores come from an LLM judge and are not validated against human annotations.",
        "",
        "---",
        "",
        "## 1. Source Publication & Hypothesis Synthesis",
        f"- **Paper ID:** `{extraction_data.get('paper_id', 'N/A')}`",
        f"- **Title:** {extraction_data.get('paper_title', 'N/A')}",
        f"- **Primary Ecological Hypothesis:** **{extraction_data.get('primary_hypothesis_name', 'N/A')}**",
        f"- **Executive Synthesis:** {extraction_data.get('hypothesis_summary', 'N/A')}",
        "",
        "---",
        "",
        "## 2. Provenance-Aware Causal Graph Edges",
        "| ID | Cause Variable | Effect Variable | Direction | Mechanism & Uncertainty | Ecological Context (Moderators) | Provenance Quote | Quote check |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]

    for edge in extraction_data.get("causal_edges", []):
        ctx = edge.get("context", {})
        ctx_str = (
            f"Temp: {ctx.get('water_temperature', 'Unspecified')}; "
            f"Flow: {ctx.get('flow_velocity', 'Unspecified')}; "
            f"Habitat: {ctx.get('habitat_structure', 'Unspecified')}"
        )
        if ctx.get("additional_moderators"):
            ctx_str += f"; Other: {ctx.get('additional_moderators')}"

        quote_clean = edge.get("provenance_quote", "").replace("|", "/").replace("\n", " ")
        lines.append(
            f"| **{edge.get('edge_id')}** | {edge.get('cause_variable')} | {edge.get('effect_variable')} | "
            f"{edge.get('causal_direction')} | {edge.get('mechanism_type')} ({edge.get('uncertainty_level')} uncertainty) | "
            f"{ctx_str} | *\"{quote_clean}\"* | {edge.get('provenance_status', 'n/a')} |"
        )

    lines.extend([
        "",
        "---",
        "",
        "## 3. Open Research Knowledge Graph (ORKG) Semantic Triples",
        "| Subject Entity | ORKG Predicate | Object Entity | Context Qualifier | Provenance Source |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ])

    for triple in extraction_data.get("orkg_triples", []):
        lines.append(
            f"| `{triple.get('subject')}` | `{triple.get('predicate')}` | `{triple.get('object')}` | "
            f"{triple.get('context_qualifier')} | {triple.get('provenance_source')} |"
        )

    if diag:
        lines.extend([
            "",
            "---",
            "",
            "## 4. Programmatic Graph Checks",
            f"- **Acyclic (DAG):** {'yes' if diag.get('is_dag') else 'NO — cycle detected'}",
            f"- **Nodes / edges:** {diag.get('n_nodes')} / {diag.get('n_edges')}",
        ])
        for path in diag.get("driver_to_outcome_paths", []):
            lines.append(
                f"- `{' → '.join(path['nodes'])}` (edges {', '.join(path['edge_ids'])}): "
                f"net effect **{path['net_effect']}**, max uncertainty {path['max_uncertainty']}"
            )
        lines.append(f"- *{diag.get('note', '')}*")

    if simulation_data and sim_params:
        lines.extend([
            "",
            "---",
            "",
            "## 5. Counterfactual Intervention Simulation (LLM reasoning + deterministic context gates)",
            f"- **Applied Thermal Shift:** {sim_params.get('temp_shift')}",
            f"- **Applied Hydrological Flow Regime:** {sim_params.get('flow_regime')}",
            f"- **Applied Habitat/Bank Intervention:** {sim_params.get('bank_restoration')}",
            f"- **Applied Water Quality Regime:** {sim_params.get('water_quality_regime')}",
            "",
            "### Simulation Verdict",
            f"- **Hypothesis Status Under Intervention:** **{simulation_data.get('hypothesis_status', 'N/A')}**",
            f"- **Predicted Ecological Invasion Risk:** **{simulation_data.get('predicted_invasion_risk', 'N/A')}**",
            f"- **Causal Chain Reasoning:** {simulation_data.get('causal_chain_reasoning', 'N/A')}",
            f"- **Actionable River Restoration Recommendation:** {simulation_data.get('management_recommendation', 'N/A')}",
            "",
            "#### Pathway-Level Impact Breakdown",
        ])
        for item in simulation_data.get("edge_by_edge_impact", []):
            lines.append(
                f"- **[{item.get('edge_id')}] {item.get('pathway')}** → *{item.get('status_under_intervention')}*: "
                f"{item.get('explanation')} — context gate: {item.get('context_gate', 'n/a')}; "
                f"consistency: {item.get('consistency', 'n/a')}"
            )

    lines.extend([
        "",
        "---",
        "",
        "## 6. Evaluation",
        f"- **Provenance Faithfulness (computed in code):** {_fmt_score(eval_metrics.get('provenance_faithfulness'))} "
        f"({eval_metrics.get('provenance_edges_exact', 0)} exact, {eval_metrics.get('provenance_edges_snapped', 0)} snapped, "
        f"{eval_metrics.get('provenance_edges_unverified', 0)} unverified of {eval_metrics.get('provenance_edges_total', 0)})",
        f"- **Causal vs. Correlational Rigor (LLM judge):** {_fmt_score(eval_metrics.get('causal_rigor_score'))}",
        f"- **Contextual Moderator Completeness (LLM judge):** {_fmt_score(eval_metrics.get('contextual_completeness'))}",
        f"- **Judge Rationale:** {eval_metrics.get('judge_rationale') or 'N/A'}",
        "",
    ])

    return "\n".join(lines)


def generate_orkg_jsonld_export(
    extraction_data: Dict[str, Any],
    simulation_data: Optional[Dict[str, Any]] = None,
) -> str:
    """
    Exports extracted causal claims and ORKG-style triples as JSON-LD for Semantic Web workflows.
    """
    payload = {
        "@context": {
            "orkg": "http://orkg.org/orkg/predicate/",
            "ecoaire": "https://tib.eu/ecoaire/ontology#",
            "prov": "http://www.w3.org/ns/prov#",
        },
        "@type": "ecoaire:ScientificHypothesisAssessment",
        "paper_id": extraction_data.get("paper_id"),
        "paper_title": extraction_data.get("paper_title"),
        "primary_hypothesis_name": extraction_data.get("primary_hypothesis_name"),
        "hypothesis_summary": extraction_data.get("hypothesis_summary"),
        "causal_edges": extraction_data.get("causal_edges", []),
        "orkg_semantic_triples": extraction_data.get("orkg_triples", []),
        "graph_diagnostics": extraction_data.get("graph_diagnostics"),
        "llm_as_a_judge_evaluation": extraction_data.get("evaluation", {}),
        "counterfactual_simulation": simulation_data or "Not executed in this session",
    }
    return json.dumps(payload, indent=2)
